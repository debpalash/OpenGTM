#!/usr/bin/env bash
set -euo pipefail

REPOSITORY_URL="${OPENGTM_REPOSITORY_URL:-https://github.com/debpalash/opengtm.git}"
INSTALL_DIR="${OPENGTM_INSTALL_DIR:-$PWD/opengtm}"
START_STACK=1

usage() {
  cat <<'EOF'
Install OpenGTM with Docker Compose.

Usage: install.sh [--dir PATH] [--no-start]

Environment:
  OPENGTM_REPOSITORY_URL  Git repository to clone
  OPENGTM_INSTALL_DIR     Install directory (default: ./opengtm)
EOF
}

while (($#)); do
  case "$1" in
    --dir) INSTALL_DIR="${2:?--dir requires a path}"; shift 2 ;;
    --no-start) START_STACK=0; shift ;;
    -h|--help) usage; exit 0 ;;
    *) echo "Unknown option: $1" >&2; usage >&2; exit 2 ;;
  esac
done

command -v git >/dev/null || { echo "git is required" >&2; exit 1; }
command -v docker >/dev/null || { echo "Docker is required: https://docs.docker.com/get-docker/" >&2; exit 1; }
docker compose version >/dev/null 2>&1 || { echo "Docker Compose v2 is required" >&2; exit 1; }

script_dir="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" 2>/dev/null && pwd || true)"
candidate_root="$(cd -- "$script_dir/.." 2>/dev/null && pwd || true)"
if [[ -f "$candidate_root/docker-compose.yml" && -f "$candidate_root/.env.example" ]]; then
  install_root="$candidate_root"
elif [[ -f "$PWD/docker-compose.yml" && -f "$PWD/.env.example" ]]; then
  install_root="$PWD"
elif [[ -f "$INSTALL_DIR/docker-compose.yml" && -f "$INSTALL_DIR/.env.example" ]]; then
  install_root="$(cd -- "$INSTALL_DIR" && pwd)"
elif [[ -e "$INSTALL_DIR" ]]; then
  echo "Install path already exists and is not an OpenGTM checkout: $INSTALL_DIR" >&2
  exit 1
else
  git clone --depth 1 "$REPOSITORY_URL" "$INSTALL_DIR"
  install_root="$(cd -- "$INSTALL_DIR" && pwd)"
fi

random_hex() {
  if command -v openssl >/dev/null; then
    openssl rand -hex "$1"
  else
    LC_ALL=C od -An -N "$1" -tx1 /dev/urandom | tr -d ' \n'
  fi
}

ip4_to_int() { local IFS=.; set -- $1; echo $(( ($1 << 24) + ($2 << 16) + ($3 << 8) + $4 )); }

# Prints the first 172.29.<251..254>.0/24 that overlaps no existing Docker network when the compose default
# (172.29.250.0/24) is taken; prints nothing when the default is free or Docker cannot be queried. Only used for a
# NEW .env, so an existing install keeps its subnet. lead_net is pinned because TRUST_PROXY_CIDRS trusts nginx's
# X-Real-IP by that range.
pick_lead_net_subnet() {
  local ids subnets third c_lo c_hi cidr net len lo hi busy
  ids="$(docker network ls -q 2>/dev/null)" || return 0
  [[ -n "$ids" ]] || return 0
  # shellcheck disable=SC2086
  subnets="$(docker network inspect $ids --format '{{range .IPAM.Config}}{{.Subnet}} {{end}}' 2>/dev/null)" || return 0
  for third in 250 251 252 253 254; do
    c_lo="$(ip4_to_int "172.29.$third.0")"; c_hi=$((c_lo + 255))
    busy=0
    for cidr in $subnets; do
      [[ "$cidr" == */* && "$cidr" != *:* ]] || continue
      net="${cidr%/*}"; len="${cidr#*/}"
      lo="$(ip4_to_int "$net")"; hi=$((lo + (1 << (32 - len)) - 1))
      if ((lo <= c_hi && hi >= c_lo)); then busy=1; break; fi
    done
    if ((busy == 0)); then
      if ((third != 250)); then echo "172.29.$third.0/24"; fi
      return 0
    fi
  done
}

cd "$install_root"
if [[ ! -d data ]]; then
  mkdir data
  # Containers use UID 1000 when installed by root; keep the bind mount writable.
  if ((EUID == 0)); then chown 1000:1000 data; fi
fi

if [[ ! -f .env ]]; then
  umask 077
  postgres_password="$(random_hex 24)"
  runtime_password="$(random_hex 24)"
  secret_key="$(random_hex 48)"
  internal_token="$(random_hex 32)"
  browser_token="$(random_hex 32)"
  app_uid="$(id -u)"
  app_gid="$(id -g)"
  if ((app_uid == 0)); then app_uid=1000; app_gid=1000; fi
  lead_net_subnet="$(pick_lead_net_subnet)"
  cp .env.example .env
  {
    printf '\n# Generated by scripts/install.sh\n'
    printf 'APP_ENV=local\n'
    printf 'SECRET_KEY=%s\n' "$secret_key"
    printf 'INTERNAL_SERVICE_TOKEN=%s\nBROWSER_SERVICE_TOKEN=%s\n' "$internal_token" "$browser_token"
    printf 'POSTGRES_USER=yupcha\nPOSTGRES_PASSWORD=%s\nPOSTGRES_DB=yupcha\n' "$postgres_password"
    printf 'DATABASE_URL=postgresql://yupcha:%s@postgres:5432/yupcha\n' "$postgres_password"
    printf 'YUPCHA_RUNTIME_DB_USER=yupcha_runtime\nYUPCHA_RUNTIME_DB_PASSWORD=%s\n' "$runtime_password"
    printf 'APP_UID=%s\nAPP_GID=%s\n' "$app_uid" "$app_gid"
    if [[ -n "$lead_net_subnet" ]]; then
      printf '# 172.29.250.0/24 (the default) overlaps another Docker network on this machine\nLEAD_NET_SUBNET=%s\n' "$lead_net_subnet"
    fi
  } >> .env
  echo "Created $install_root/.env (no default admin account is created)"
else
  echo "Keeping existing $install_root/.env"
fi

if ((START_STACK)); then
  docker compose up -d --build
  docker compose ps
  echo "OpenGTM is starting at http://localhost:3000"
  echo "First run: open http://localhost:3000/setup and create the admin account."
  echo "The one-time setup token is in the API log: docker compose logs api-go | grep -i 'setup token'"
  echo "(or set SETUP_TOKEN in .env before starting)."
else
  echo "Configured $install_root; run: cd '$install_root' && docker compose up -d --build"
fi
