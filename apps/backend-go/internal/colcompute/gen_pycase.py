#!/usr/bin/env python3
"""Generates pycase_table.go: CPython str.upper/lower/title full case mappings.

Run from this directory with the Python version the legacy backend runs on:
    python3 gen_pycase.py > pycase_table.go
Only code points whose single-character mapping differs from the identity are
listed. Unicode data comes from the generating interpreter (printed in the header).
"""
import sys
import unicodedata


def lit(s):
    return '"' + "".join(c if (32 <= ord(c) < 127 and c not in '"\\') else "\\U%08x" % ord(c) for c in s) + '"'


def table(name, fn):
    out = ["var %s = map[rune]string{" % name]
    for cp in range(0x110000):
        if 0xD800 <= cp <= 0xDFFF:
            continue
        c = chr(cp)
        m = fn(c)
        if m != c:
            out.append("\t0x%x: %s," % (cp, lit(m)))
    out.append("}")
    return "\n".join(out)


print("// Code generated by gen_pycase.py (Python %s, Unicode %s); DO NOT EDIT.\n" % (sys.version.split()[0], unicodedata.unidata_version))
print("package colcompute\n")
print("// pyUpperMap, pyLowerMap and pyTitleMap hold CPython's full (SpecialCasing) single-character mappings.")
print(table("pyUpperMap", str.upper))
print()
print(table("pyLowerMap", str.lower))
print()
print(table("pyTitleMap", str.title))
